// Builds src/data/priceList.json (PUBLIC: final website prices only) from the
// private rate sheet private/price-source.csv (NOT committed - it holds the
// pandit's own/wholesale rates).   Usage:  npm run build:price-list
//
// CSV columns: no,name_hi,name_en,category,status,price_type,base_min,base_max,unit,note
//   status: approved -> price is shown publicly | verify -> listed, "price on WhatsApp"
//           ask -> listed, "price on request"
// Rows whose note says "name unclear" are left OUT of the public list entirely.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { publicPrice, MARKUP_PERCENT } from '../src/utils/pricing.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'private', 'price-source.csv');
const OUT = join(ROOT, 'src', 'data', 'priceList.json');

// The consultation price is set by the owner as a FINAL price (not derived from a base rate).
const CONSULTATION_FINAL_PRICE = 501;

function parseCsv(text) {
    const rows = []; let row = [], field = '', q = false;
    for (let i = 0; i < text.length; i++) {
        const c = text[i];
        if (q) {
            if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
            else if (c === '"') q = false;
            else field += c;
        } else if (c === '"') q = true;
        else if (c === ',') { row.push(field); field = ''; }
        else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
        else if (c !== '\r') field += c;
    }
    if (field || row.length) { row.push(field); rows.push(row); }
    return rows;
}

if (!existsSync(SRC)) {
    console.error(`Missing ${SRC}. Put the private rate sheet there (see README in docs/) - nothing was changed.`);
    process.exit(1);
}
const [header, ...data] = parseCsv(readFileSync(SRC, 'utf8')).filter(r => r.length > 1);
const idx = Object.fromEntries(header.map((h, i) => [h.trim(), i]));
const num = v => (v === '' || v == null ? null : Number(v));

const items = [];
const problems = [];
for (const r of data) {
    const rec = Object.fromEntries(Object.keys(idx).map(k => [k, (r[idx[k]] || '').trim()]));
    const no = Number(rec.no);
    const status = rec.status;
    if (!['approved', 'verify', 'ask'].includes(status)) problems.push(`#${no}: bad status "${status}"`);
    if (/name unclear/i.test(rec.note)) continue; // keep unreviewed/unclear names off the public site

    const item = { no, nameHi: rec.name_hi, nameEn: rec.name_en, category: rec.category, status, unit: rec.unit, priceType: 'none', min: null, max: null };
    if (status === 'approved') {
        const lo = num(rec.base_min), hi = num(rec.base_max);
        if (!(lo > 0) || !(hi >= lo)) { problems.push(`#${no}: approved item needs base_min>0 and base_max>=base_min`); continue; }
        item.min = publicPrice(lo);
        item.max = publicPrice(hi);
        item.priceType = item.min === item.max ? 'fixed' : 'range';
    }
    items.push(item);
}
if (problems.length) { console.error('PROBLEMS:\n' + problems.join('\n')); process.exit(1); }
items.sort((a, b) => a.no - b.no);

const out = {
    _readme: 'GENERATED by scripts/build-price-list.mjs from the private rate sheet. Contains FINAL PUBLIC prices only. Do not edit by hand.',
    markupPercent: MARKUP_PERCENT,
    consultation: { nameHi: 'ज्योतिष परामर्श (व्यक्तिगत सत्र)', nameEn: 'Astrology Consultation (personal session)', price: CONSULTATION_FINAL_PRICE, unit: 'session' },
    categories: [
        { id: 'A', nameHi: 'पाठ, स्तोत्र एवं धार्मिक पाठ', nameEn: 'Paath, Stotra & Sacred Recitations' },
        { id: 'B', nameHi: 'श्राद्ध, शांति एवं संस्कार', nameEn: 'Shraddh, Shanti & Sanskar' },
        { id: 'C', nameHi: 'मंत्र जाप एवं ग्रह जाप', nameEn: 'Mantra Jaap & Graha Jaap' },
        { id: 'D', nameHi: 'यज्ञ, पूजन एवं विशेष अनुष्ठान', nameEn: 'Yagya, Pujan & Special Rituals' },
    ],
    items,
};
writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
const c = s => items.filter(i => i.status === s).length;
console.log(`priceList.json written: ${items.length} public items (${c('approved')} priced, ${c('verify')} price-on-WhatsApp, ${c('ask')} on request) + consultation Rs ${CONSULTATION_FINAL_PRICE}.`);
